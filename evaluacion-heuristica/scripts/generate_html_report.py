def load_findings(path: str) -> Tuple[List[Dict], Dict]:
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data.get("findings", []), data.get("context", {})


def calculate(findings: List[Dict]) -> Tuple[float, Dict[int, int], Dict[str, float]]:
    total = len(findings)
    if total == 0:
        return 0.0, {}, {}

    distribution = {4: 0, 3: 0, 2: 0, 1: 0, 0: 0}
    severity_sum = 0
    for f in findings:
        s = f.get("severity", 0)
        distribution[s] = distribution.get(s, 0) + 1
        severity_sum += s

    avg = severity_sum / total
    score = round(10 - avg, 1)
    alerts = {
        "critical_pct": round(distribution[4] / total * 100, 1),
        "major_pct": round(distribution[3] / total * 100, 1),
    }
    return score, distribution, alerts


def interpret_score(score: float) -> str:
    if score >= 9.0:
        return "Excelente"
    if score >= 7.0:
        return "Bueno"
    if score >= 5.0:
        return "Regular"
    if score >= 3.0:
        return "Malo"
    return "Crítico"


def build_matrix(findings: List[Dict]) -> Tuple[List, List, List, List]:
    qw, mp, fi, tl = [], [], [], []
    for f in findings:
        effort = EFFORT_ORDER.get(f.get("effort", "Medio"), 2)
        severity = f.get("severity", 2)
        if severity >= 3 and effort <= 2:
            qw.append(f)
        elif severity >= 3 and effort > 2:
            mp.append(f)
        elif severity < 3 and effort <= 2:
            fi.append(f)
        else:
            tl.append(f)
    return qw, mp, fi, tl


def most_violated_heuristic(findings: List[Dict]) -> str:
    counts: Dict[str, int] = {}
    for f in findings:
        h = f.get("heuristic", "H?")
        counts[h] = counts.get(h, 0) + 1
    if not counts:
        return "—"
    max_count = max(counts.values())
    top = [h for h, c in counts.items() if c == max_count]
    return f"{', '.join(top)} ({max_count} hallazgos)"


def severity_bar_svg(distribution: Dict[int, int], total: int) -> str:
    bars = []
    colors = {4: "#dc2626", 3: "#f59e0b", 2: "#3b82f6", 1: "#6b7280", 0: "#d1d5db"}
    labels = {4: "Catastrófico", 3: "Mayor", 2: "Menor", 1: "Cosmético", 0: "Sin problema"}
    max_count = max(distribution.values()) if distribution else 1

    for level in (4, 3, 2, 1, 0):
        count = distribution.get(level, 0)
        pct = round(count / total * 100, 1) if total else 0
        bar_height = (count / max_count) * 120 if max_count else 0
        bar_height = max(bar_height, 4)
        bars.append(f"""
        <div style="display:flex;align-items:end;gap:8px;margin-bottom:6px">
          <div style="width:120px;text-align:right;font-size:12px;color:#374151">{labels[level]}</div>
          <div style="flex:1;height:20px;background:#e5e7eb;border-radius:4px;overflow:hidden">
            <div style="height:100%;width:{pct}%;background:{colors[level]};border-radius:4px;min-width:4px"></div>
          </div>
          <div style="width:80px;font-size:12px;color:#6b7280">{count} ({pct}%)</div>
        </div>""")
    return "\n".join(bars)


