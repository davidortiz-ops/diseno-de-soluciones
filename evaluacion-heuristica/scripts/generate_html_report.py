def main() -> int:
    parser = argparse.ArgumentParser(
        description="Genera reporte HTML de evaluación heurística desde findings JSON"
    )
    parser.add_argument("input", help="Archivo JSON con hallazgos")
    parser.add_argument("--output", "-o", required=True, help="Archivo HTML de salida")
    parser.add_argument("--template", "-t", choices=["completa", "ejecutiva"],
                        default="completa", help="Tipo de reporte")
    parser.add_argument("--lang", "-l", choices=["es", "en"], default="es",
                        help="Idioma del reporte")
    args = parser.parse_args()

    path = Path(args.input)
    if not path.exists():
        print(f"Error: no se encuentra el archivo {path}", file=sys.stderr)
        return 1

    try:
        findings, context = load_findings(args.input)
    except json.JSONDecodeError as e:
        print(f"Error: JSON inválido — {e}", file=sys.stderr)
        return 1

    score, distribution, alerts = calculate(findings)
    html = generate(findings, context, score, distribution, alerts,
                    args.template, args.lang)

    out_path = Path(args.output)
    out_path.write_text(html, encoding="utf-8")
    print(f"Reporte HTML generado: {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
